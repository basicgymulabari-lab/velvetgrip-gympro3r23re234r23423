-- Production SaaS hardening for IronVault.
--
-- The UI still keeps a compact JSON workspace for backwards compatibility,
-- but the workspace is now owned by a gym tenant rather than by a browser or
-- by a client-supplied owner id. All reads/writes go through SECURITY DEFINER
-- RPCs that derive the gym from auth.uid(). Receptionists receive a filtered
-- workspace and writes are merged server-side according to their permissions.

create extension if not exists pgcrypto with schema extensions;

create table if not exists public.gyms (
  id uuid primary key default gen_random_uuid(),
  owner_user_id uuid not null unique references auth.users(id) on delete cascade,
  name text not null check (char_length(trim(name)) between 2 and 120),
  subscription_plan text not null default 'free' check (subscription_plan in ('free', 'pro')),
  subscription_status text not null default 'free'
    check (subscription_status in ('free', 'trialing', 'active', 'past_due', 'canceled', 'expired')),
  trial_ends_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.gym_users (
  gym_id uuid not null references public.gyms(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('owner', 'receptionist')),
  display_name text not null default '',
  email text not null default '',
  enabled boolean not null default true,
  permissions jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (gym_id, user_id)
);

-- The current product supports one gym workspace per login. Keeping this
-- invariant removes ambiguous tenant selection and can be relaxed later when a
-- deliberate multi-location switcher is introduced.
create unique index if not exists gym_users_one_gym_per_user_idx
  on public.gym_users (user_id);
create index if not exists gym_users_gym_role_idx on public.gym_users (gym_id, role);

alter table public.gym_workspaces add column if not exists gym_id uuid references public.gyms(id) on delete cascade;
alter table public.gym_workspaces add column if not exists revision bigint not null default 1;

-- Backfill every legacy owner workspace into a real tenant.
insert into public.gyms (owner_user_id, name)
select
  workspace.owner_id,
  coalesce(nullif(trim(workspace.state -> 'settings' ->> 'gymName'), ''), 'My Gym')
from public.gym_workspaces workspace
on conflict (owner_user_id) do nothing;

insert into public.gym_users (gym_id, user_id, role, display_name, email, enabled, permissions)
select
  gym.id,
  gym.owner_user_id,
  'owner',
  coalesce(nullif(trim(workspace.state -> 'settings' ->> 'adminName'), ''), 'Gym Owner'),
  coalesce(nullif(trim(workspace.state -> 'settings' ->> 'email'), ''), ''),
  true,
  '{}'::jsonb
from public.gyms gym
join public.gym_workspaces workspace on workspace.owner_id = gym.owner_user_id
on conflict (gym_id, user_id) do update set
  role = 'owner',
  enabled = true,
  updated_at = now();

update public.gym_workspaces workspace
set gym_id = gym.id
from public.gyms gym
where workspace.gym_id is null
  and gym.owner_user_id = workspace.owner_id;

alter table public.gym_workspaces alter column gym_id set not null;
create unique index if not exists gym_workspaces_gym_id_idx on public.gym_workspaces (gym_id);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  gym_id uuid not null references public.gyms(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  role text not null check (role in ('owner', 'receptionist', 'system')),
  action text not null,
  entity_type text,
  entity_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists audit_logs_gym_created_idx on public.audit_logs (gym_id, created_at desc);
create index if not exists audit_logs_gym_action_idx on public.audit_logs (gym_id, action, created_at desc);

-- Durable rate-limit counters used by trusted server routes. Normal app users
-- cannot read or manipulate these counters.
create table if not exists public.api_rate_limits (
  scope text not null,
  subject text not null,
  window_started_at timestamptz not null default now(),
  request_count integer not null default 0,
  updated_at timestamptz not null default now(),
  primary key (scope, subject)
);

alter table public.gyms enable row level security;
alter table public.gym_users enable row level security;
alter table public.audit_logs enable row level security;
alter table public.api_rate_limits enable row level security;

create or replace function public.iv_current_gym_id()
returns uuid
language sql
stable
security definer
set search_path = public
as $$
  select membership.gym_id
  from public.gym_users membership
  where membership.user_id = auth.uid()
    and membership.enabled
  order by case membership.role when 'owner' then 0 else 1 end
  limit 1
$$;

create or replace function public.iv_is_current_gym_owner()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.gym_users membership
    where membership.user_id = auth.uid()
      and membership.gym_id = public.iv_current_gym_id()
      and membership.role = 'owner'
      and membership.enabled
  )
$$;

create or replace function public.iv_has_permission(p_permissions jsonb, p_key text)
returns boolean
language sql
immutable
set search_path = ''
as $$
  select coalesce((p_permissions ->> p_key)::boolean, false)
$$;

drop policy if exists "Members can read their gym" on public.gyms;
create policy "Members can read their gym"
  on public.gyms for select to authenticated
  using (id = public.iv_current_gym_id());

drop policy if exists "Owners can update their gym" on public.gyms;
create policy "Owners can update their gym"
  on public.gyms for update to authenticated
  using (id = public.iv_current_gym_id() and public.iv_is_current_gym_owner())
  with check (id = public.iv_current_gym_id() and public.iv_is_current_gym_owner());

drop policy if exists "Members can read permitted staff records" on public.gym_users;
create policy "Members can read permitted staff records"
  on public.gym_users for select to authenticated
  using (
    user_id = auth.uid()
    or (gym_id = public.iv_current_gym_id() and public.iv_is_current_gym_owner())
  );

drop policy if exists "Owners can read audit logs" on public.audit_logs;
create policy "Owners can read audit logs"
  on public.audit_logs for select to authenticated
  using (gym_id = public.iv_current_gym_id() and public.iv_is_current_gym_owner());

-- Client code must not access the raw JSON workspace. In particular, a
-- receptionist with product access but without cost permission must never be
-- able to reveal costs by bypassing the UI and querying PostgREST directly.
drop policy if exists "Owners can read their gym workspace" on public.gym_workspaces;
drop policy if exists "Owners can create their gym workspace" on public.gym_workspaces;
drop policy if exists "Owners can update their gym workspace" on public.gym_workspaces;
drop policy if exists "Owners can delete their gym workspace" on public.gym_workspaces;
revoke all on public.gym_workspaces from anon, authenticated;
revoke all on public.api_rate_limits from anon, authenticated;

create or replace function public.iv_validate_workspace(p_state jsonb)
returns void
language plpgsql
immutable
set search_path = public
as $$
declare
  v_key text;
begin
  if p_state is null or jsonb_typeof(p_state) <> 'object' then
    raise exception 'INVALID_WORKSPACE';
  end if;
  if coalesce((p_state ->> 'version')::integer, 0) <> 1 then
    raise exception 'INVALID_WORKSPACE_VERSION';
  end if;
  if pg_column_size(p_state) > 50 * 1024 * 1024 then
    raise exception 'WORKSPACE_TOO_LARGE';
  end if;

  foreach v_key in array array[
    'members','plans','memberships','payments','products','sales','activities',
    'expenses','inquiries','readNotifications'
  ] loop
    if jsonb_typeof(coalesce(p_state -> v_key, '[]'::jsonb)) <> 'array' then
      raise exception 'INVALID_WORKSPACE_ARRAY:%', v_key;
    end if;
  end loop;

  foreach v_key in array array[
    'members','plans','memberships','payments','products','sales','expenses','inquiries'
  ] loop
    if exists (
      select 1
      from jsonb_array_elements(coalesce(p_state -> v_key, '[]'::jsonb)) item
      group by item ->> 'id'
      having nullif(item ->> 'id', '') is null or count(*) > 1
    ) then
      raise exception 'DUPLICATE_OR_MISSING_ID:%', v_key;
    end if;
  end loop;

  if exists (
    select 1
    from jsonb_array_elements(coalesce(p_state -> 'memberships', '[]'::jsonb)) membership
    where not exists (
      select 1 from jsonb_array_elements(coalesce(p_state -> 'members', '[]'::jsonb)) member
      where member ->> 'id' = membership ->> 'memberId'
    )
    or not exists (
      select 1 from jsonb_array_elements(coalesce(p_state -> 'plans', '[]'::jsonb)) plan
      where plan ->> 'id' = membership ->> 'planId'
    )
    or coalesce((membership ->> 'price')::numeric, -1) < 0
    or coalesce((membership ->> 'discount')::numeric, -1) < 0
    or coalesce((membership ->> 'joiningFee')::numeric, 0) < 0
    or coalesce((membership ->> 'discount')::numeric, 0) > coalesce((membership ->> 'price')::numeric, 0)
    or (membership ->> 'endDate')::timestamptz < (membership ->> 'startDate')::timestamptz
  ) then
    raise exception 'INVALID_MEMBERSHIP_DATA';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(coalesce(p_state -> 'payments', '[]'::jsonb)) payment
    where coalesce((payment ->> 'amount')::numeric, 0) <= 0
      or coalesce((payment ->> 'amount')::numeric, 0) > 1000000000000
      or (
        nullif(payment ->> 'memberId', '') is not null
        and not exists (
          select 1 from jsonb_array_elements(coalesce(p_state -> 'members', '[]'::jsonb)) member
          where member ->> 'id' = payment ->> 'memberId'
        )
      )
      or (
        nullif(payment ->> 'membershipId', '') is not null
        and not exists (
          select 1 from jsonb_array_elements(coalesce(p_state -> 'memberships', '[]'::jsonb)) membership
          where membership ->> 'id' = payment ->> 'membershipId'
        )
      )
      or (
        nullif(payment ->> 'saleId', '') is not null
        and not exists (
          select 1 from jsonb_array_elements(coalesce(p_state -> 'sales', '[]'::jsonb)) sale
          where sale ->> 'id' = payment ->> 'saleId'
        )
      )
  ) then
    raise exception 'INVALID_PAYMENT_DATA';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(coalesce(p_state -> 'products', '[]'::jsonb)) product
    where coalesce((product ->> 'price')::numeric, -1) < 0
      or coalesce((product ->> 'cost')::numeric, -1) < 0
      or coalesce((product ->> 'stock')::numeric, -1) < 0
      or coalesce((product ->> 'stock')::numeric, 0) <> trunc(coalesce((product ->> 'stock')::numeric, 0))
  ) then
    raise exception 'INVALID_PRODUCT_DATA';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(coalesce(p_state -> 'sales', '[]'::jsonb)) sale
    where coalesce((sale ->> 'qty')::numeric, 0) <= 0
      or coalesce((sale ->> 'qty')::numeric, 0) <> trunc(coalesce((sale ->> 'qty')::numeric, 0))
      or coalesce((sale ->> 'unitPrice')::numeric, -1) < 0
      or coalesce((sale ->> 'unitCost')::numeric, -1) < 0
      or coalesce((sale ->> 'discount')::numeric, -1) < 0
      or coalesce((sale ->> 'total')::numeric, -1) < 0
      or coalesce((sale ->> 'paid')::numeric, 0) < 0
      or coalesce((sale ->> 'paid')::numeric, 0) > coalesce((sale ->> 'total')::numeric, 0)
  ) then
    raise exception 'INVALID_SALE_DATA';
  end if;

  if exists (
    select 1
    from jsonb_array_elements(coalesce(p_state -> 'expenses', '[]'::jsonb)) expense
    where coalesce((expense ->> 'amount')::numeric, 0) <= 0
      or coalesce((expense ->> 'amount')::numeric, 0) > 1000000000000
  ) then
    raise exception 'INVALID_EXPENSE_DATA';
  end if;

  if coalesce((p_state ->> 'invoiceSeq')::numeric, -1) < 0
     or coalesce((p_state ->> 'invoiceSeq')::numeric, 0) <> trunc(coalesce((p_state ->> 'invoiceSeq')::numeric, 0)) then
    raise exception 'INVALID_INVOICE_SEQUENCE';
  end if;
end;
$$;

