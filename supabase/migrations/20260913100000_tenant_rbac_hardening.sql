create or replace function public.get_current_gym_context()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_membership public.gym_users%rowtype;
  v_gym public.gyms%rowtype;
begin
  if v_user is null then
    return null;
  end if;

  select * into v_membership
  from public.gym_users
  where user_id = v_user
  limit 1;
  if not found then
    return null;
  end if;

  select * into v_gym from public.gyms where id = v_membership.gym_id;
  return jsonb_build_object(
    'gym_id', v_membership.gym_id,
    'role', v_membership.role,
    'permissions', coalesce(v_membership.permissions, '{}'::jsonb),
    'display_name', v_membership.display_name,
    'email', v_membership.email,
    'enabled', v_membership.enabled,
    'gym_name', v_gym.name
  );
end;
$$;

create or replace function public.ensure_owner_gym(p_name text, p_initial_state jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_gym_id uuid;
  v_existing_role text;
  v_name text := left(coalesce(nullif(trim(p_name), ''), 'My Gym'), 120);
  v_display_name text := left(coalesce(nullif(trim(p_initial_state -> 'settings' ->> 'adminName'), ''), 'Gym Owner'), 120);
  v_email text := left(coalesce(nullif(trim(p_initial_state -> 'settings' ->> 'email'), ''), ''), 320);
  v_state jsonb;
begin
  if v_user is null then
    raise exception 'AUTH_REQUIRED';
  end if;

  select gym_id, role into v_gym_id, v_existing_role
  from public.gym_users
  where user_id = v_user
  limit 1;
  if found then
    return public.get_current_gym_context();
  end if;

  insert into public.gyms (owner_user_id, name)
  values (v_user, v_name)
  on conflict (owner_user_id) do update set updated_at = now()
  returning id into v_gym_id;

  insert into public.gym_users (gym_id, user_id, role, display_name, email, enabled, permissions)
  values (v_gym_id, v_user, 'owner', v_display_name, v_email, true, '{}'::jsonb)
  on conflict (gym_id, user_id) do update set
    role = 'owner', enabled = true, display_name = excluded.display_name,
    email = excluded.email, updated_at = now();

  v_state := coalesce(p_initial_state, '{}'::jsonb) - 'auth' - 'staff';
  v_state := jsonb_set(v_state, '{auth}', '{"email":"","passwordHash":""}'::jsonb, true);
  v_state := jsonb_set(v_state, '{staff}', '{}'::jsonb, true);

  insert into public.gym_workspaces (owner_id, gym_id, state, revision)
  values (v_user, v_gym_id, v_state, 1)
  on conflict (gym_id) do nothing;

  insert into public.audit_logs (gym_id, user_id, role, action, entity_type, entity_id)
  values (v_gym_id, v_user, 'owner', 'gym_created', 'gym', v_gym_id::text);

  return public.get_current_gym_context();
end;
$$;

create or replace function public.load_current_gym_workspace()
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_membership public.gym_users%rowtype;
  v_workspace public.gym_workspaces%rowtype;
  v_state jsonb;
  v_products jsonb;
  v_sales jsonb;
  v_can_members boolean;
  v_can_memberships boolean;
  v_can_payments boolean;
  v_can_products boolean;
  v_can_reports boolean;
  v_can_notifications boolean;
  v_can_dashboard boolean;
begin
  if v_user is null then
    raise exception 'AUTH_REQUIRED';
  end if;

  select * into v_membership
  from public.gym_users
  where user_id = v_user
  limit 1;
  if not found then
    return null;
  end if;
  if not v_membership.enabled then
    raise exception 'STAFF_DISABLED';
  end if;

  select * into v_workspace
  from public.gym_workspaces
  where gym_id = v_membership.gym_id;
  if not found then
    return null;
  end if;

  v_state := coalesce(v_workspace.state, '{}'::jsonb) - 'auth' - 'staff';
  v_state := jsonb_set(v_state, '{auth}', '{"email":"","passwordHash":""}'::jsonb, true);
  v_state := jsonb_set(v_state, '{staff}', '{}'::jsonb, true);

  if v_membership.role = 'receptionist' then
    v_can_members := public.iv_has_permission(v_membership.permissions, 'members');
    v_can_memberships := public.iv_has_permission(v_membership.permissions, 'memberships');
    v_can_payments := public.iv_has_permission(v_membership.permissions, 'payments');
    v_can_products := public.iv_has_permission(v_membership.permissions, 'products');
    v_can_reports := public.iv_has_permission(v_membership.permissions, 'reports');
    v_can_notifications := public.iv_has_permission(v_membership.permissions, 'notifications');
    v_can_dashboard := public.iv_has_permission(v_membership.permissions, 'dashboard');

    if not (v_can_members or v_can_memberships or v_can_payments or v_can_products or v_can_reports or v_can_notifications) then
      v_state := jsonb_set(v_state, '{members}', '[]'::jsonb, true);
    end if;
    if not (v_can_memberships or v_can_payments or v_can_reports or v_can_notifications) then
      v_state := jsonb_set(v_state, '{memberships}', '[]'::jsonb, true);
      v_state := jsonb_set(v_state, '{plans}', '[]'::jsonb, true);
    end if;
    if not (v_can_payments or v_can_reports or v_can_notifications or (v_can_dashboard and public.iv_has_permission(v_membership.permissions, 'viewRevenue'))) then
      v_state := jsonb_set(v_state, '{payments}', '[]'::jsonb, true);
    end if;
    if not (v_can_products or v_can_reports or v_can_notifications) then
      v_state := jsonb_set(v_state, '{products}', '[]'::jsonb, true);
    end if;
    if not (v_can_products or v_can_payments or v_can_reports or (v_can_dashboard and public.iv_has_permission(v_membership.permissions, 'viewRevenue'))) then
      v_state := jsonb_set(v_state, '{sales}', '[]'::jsonb, true);
    end if;
    if not (public.iv_has_permission(v_membership.permissions, 'expenses') or v_can_reports) then
      v_state := jsonb_set(v_state, '{expenses}', '[]'::jsonb, true);
    end if;
    if not (public.iv_has_permission(v_membership.permissions, 'inquiries') or v_can_notifications) then
      v_state := jsonb_set(v_state, '{inquiries}', '[]'::jsonb, true);
    end if;
    if not v_can_notifications then
      v_state := jsonb_set(v_state, '{readNotifications}', '[]'::jsonb, true);
    end if;
    if not (v_can_dashboard or v_can_notifications) then
      v_state := jsonb_set(v_state, '{activities}', '[]'::jsonb, true);
    end if;

    -- Product costs and historical cost-of-goods are owner-sensitive unless
    -- the owner explicitly grants the cost/profit permission.
    if not public.iv_has_permission(v_membership.permissions, 'viewProductCost') then
      select coalesce(jsonb_agg(jsonb_set(item, '{cost}', '0'::jsonb, true)), '[]'::jsonb)
      into v_products
      from jsonb_array_elements(coalesce(v_state -> 'products', '[]'::jsonb)) item;
      select coalesce(jsonb_agg(jsonb_set(item, '{unitCost}', '0'::jsonb, true)), '[]'::jsonb)
      into v_sales
      from jsonb_array_elements(coalesce(v_state -> 'sales', '[]'::jsonb)) item;
      v_state := jsonb_set(v_state, '{products}', coalesce(v_products, '[]'::jsonb), true);
      v_state := jsonb_set(v_state, '{sales}', coalesce(v_sales, '[]'::jsonb), true);
    end if;

    -- Staff never need owner account identity fields from workspace settings.
    v_state := jsonb_set(
      v_state,
      '{settings,adminName}',
      to_jsonb('Gym Owner'::text),
      true
    );
  end if;

  return jsonb_build_object(
    'gym_id', v_membership.gym_id,
    'role', v_membership.role,
    'permissions', coalesce(v_membership.permissions, '{}'::jsonb),
    'display_name', v_membership.display_name,
    'email', v_membership.email,
    'revision', v_workspace.revision,
    'state', v_state
  );
end;
$$;

create or replace function public.save_current_gym_workspace(p_state jsonb, p_expected_revision bigint)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_membership public.gym_users%rowtype;
  v_workspace public.gym_workspaces%rowtype;
  v_next jsonb;
  v_products jsonb;
  v_sales jsonb;
  v_invoice_seq bigint;
  v_changed_keys jsonb;
begin
  if v_user is null then raise exception 'AUTH_REQUIRED'; end if;
  if p_state is null or jsonb_typeof(p_state) <> 'object' then raise exception 'INVALID_WORKSPACE'; end if;

  select * into v_membership
  from public.gym_users
  where user_id = v_user
  limit 1;
  if not found then raise exception 'GYM_MEMBERSHIP_REQUIRED'; end if;
  if not v_membership.enabled then raise exception 'STAFF_DISABLED'; end if;

  select * into v_workspace
  from public.gym_workspaces
  where gym_id = v_membership.gym_id
  for update;
  if not found then raise exception 'WORKSPACE_NOT_FOUND'; end if;

  if p_expected_revision is null or p_expected_revision <> v_workspace.revision then
    raise exception 'WORKSPACE_CONFLICT';
  end if;

  if v_membership.role = 'owner' then
    v_next := p_state - 'auth' - 'staff';
    v_next := jsonb_set(v_next, '{auth}', '{"email":"","passwordHash":""}'::jsonb, true);
    v_next := jsonb_set(v_next, '{staff}', '{}'::jsonb, true);
  else
    -- Start from the authoritative server state and only replace areas the
    -- owner explicitly delegated. This prevents client-side privilege bypasses
    -- and prevents hidden fields from being zeroed by a filtered client copy.
    v_next := v_workspace.state;

    if public.iv_has_permission(v_membership.permissions, 'members') then
      v_next := jsonb_set(v_next, '{members}', coalesce(p_state -> 'members', '[]'::jsonb), true);
    end if;
    if public.iv_has_permission(v_membership.permissions, 'memberships') then
      v_next := jsonb_set(v_next, '{memberships}', coalesce(p_state -> 'memberships', '[]'::jsonb), true);
      v_next := jsonb_set(v_next, '{plans}', coalesce(p_state -> 'plans', '[]'::jsonb), true);
    end if;
    if public.iv_has_permission(v_membership.permissions, 'payments') then
      -- Receptionists may record new payments but cannot rewrite or remove
      -- financial history by crafting a workspace payload outside the UI.
      if exists (
        select 1
        from jsonb_array_elements(coalesce(v_workspace.state -> 'payments', '[]'::jsonb)) original
        where not exists (
          select 1
          from jsonb_array_elements(coalesce(p_state -> 'payments', '[]'::jsonb)) incoming
          where incoming ->> 'id' = original ->> 'id' and incoming = original
        )
      ) then
        raise exception 'PAYMENT_HISTORY_IMMUTABLE';
      end if;
      v_next := jsonb_set(v_next, '{payments}', coalesce(p_state -> 'payments', '[]'::jsonb), true);
    end if;
    if public.iv_has_permission(v_membership.permissions, 'products') then
      v_products := coalesce(p_state -> 'products', '[]'::jsonb);
      v_sales := coalesce(p_state -> 'sales', '[]'::jsonb);

      -- Existing sales are accounting history. Product permission allows new
      -- sales and inventory changes, not retroactive sale edits/deletes.
      if exists (
        select 1
        from jsonb_array_elements(coalesce(v_workspace.state -> 'sales', '[]'::jsonb)) original
        where not exists (
          select 1
          from jsonb_array_elements(v_sales) incoming
          where incoming ->> 'id' = original ->> 'id' and incoming = original
        )
      ) then
        raise exception 'SALE_HISTORY_IMMUTABLE';
      end if;

      if not public.iv_has_permission(v_membership.permissions, 'viewProductCost') then
        select coalesce(jsonb_agg(
          jsonb_set(
            incoming,
            '{cost}',
            coalesce(
              (select original -> 'cost'
               from jsonb_array_elements(coalesce(v_workspace.state -> 'products', '[]'::jsonb)) original
               where original ->> 'id' = incoming ->> 'id'
               limit 1),
              '0'::jsonb
            ),
            true
          )
        ), '[]'::jsonb)
        into v_products
        from jsonb_array_elements(v_products) incoming;

        select coalesce(jsonb_agg(
          jsonb_set(
            incoming,
            '{unitCost}',
            coalesce(
              (select original -> 'unitCost'
               from jsonb_array_elements(coalesce(v_workspace.state -> 'sales', '[]'::jsonb)) original
               where original ->> 'id' = incoming ->> 'id'
               limit 1),
              (select product -> 'cost'
               from jsonb_array_elements(coalesce(v_workspace.state -> 'products', '[]'::jsonb)) product
               where product ->> 'id' = incoming ->> 'productId'
               limit 1),
              '0'::jsonb
            ),
            true
          )
        ), '[]'::jsonb)
        into v_sales
        from jsonb_array_elements(v_sales) incoming;
      end if;

      v_next := jsonb_set(v_next, '{products}', coalesce(v_products, '[]'::jsonb), true);
      v_next := jsonb_set(v_next, '{sales}', coalesce(v_sales, '[]'::jsonb), true);
    end if;
    if public.iv_has_permission(v_membership.permissions, 'expenses') then
      v_next := jsonb_set(v_next, '{expenses}', coalesce(p_state -> 'expenses', '[]'::jsonb), true);
    end if;
    if public.iv_has_permission(v_membership.permissions, 'inquiries') then
      v_next := jsonb_set(v_next, '{inquiries}', coalesce(p_state -> 'inquiries', '[]'::jsonb), true);
    end if;
    if public.iv_has_permission(v_membership.permissions, 'notifications') then
      v_next := jsonb_set(v_next, '{readNotifications}', coalesce(p_state -> 'readNotifications', '[]'::jsonb), true);
    end if;

    if public.iv_has_permission(v_membership.permissions, 'members')
       or public.iv_has_permission(v_membership.permissions, 'memberships')
       or public.iv_has_permission(v_membership.permissions, 'payments')
       or public.iv_has_permission(v_membership.permissions, 'products')
       or public.iv_has_permission(v_membership.permissions, 'expenses')
       or public.iv_has_permission(v_membership.permissions, 'inquiries') then
      v_next := jsonb_set(v_next, '{activities}', coalesce(p_state -> 'activities', '[]'::jsonb), true);
    end if;

    -- Invoice numbers are shared by payments and product sales. They may only
    -- move forward and only by users allowed to create those records.
    if public.iv_has_permission(v_membership.permissions, 'payments')
       or public.iv_has_permission(v_membership.permissions, 'products') then
      v_invoice_seq := greatest(
        coalesce((v_workspace.state ->> 'invoiceSeq')::bigint, 0),
        coalesce((p_state ->> 'invoiceSeq')::bigint, 0)
      );
      v_next := jsonb_set(v_next, '{invoiceSeq}', to_jsonb(v_invoice_seq), true);
    end if;

    v_next := v_next - 'auth' - 'staff';
    v_next := jsonb_set(v_next, '{auth}', '{"email":"","passwordHash":""}'::jsonb, true);
    v_next := jsonb_set(v_next, '{staff}', '{}'::jsonb, true);
  end if;

  select coalesce(jsonb_agg(changed.key), '[]'::jsonb)
  into v_changed_keys
  from (
    select entry.key
    from jsonb_object_keys(v_next) as entry(key)
    where (v_workspace.state -> entry.key) is distinct from (v_next -> entry.key)
  ) changed;

  update public.gym_workspaces
  set state = v_next,
      revision = revision + 1,
      updated_at = now()
  where id = v_workspace.id
  returning revision into v_workspace.revision;

  update public.gyms
  set name = coalesce(nullif(trim(v_next -> 'settings' ->> 'gymName'), ''), name),
      updated_at = now()
  where id = v_membership.gym_id
    and v_membership.role = 'owner';

  insert into public.audit_logs (gym_id, user_id, role, action, entity_type, entity_id, metadata)
  values (
    v_membership.gym_id,
    v_user,
    v_membership.role,
    'workspace_updated',
    'workspace',
    v_workspace.id::text,
    jsonb_build_object('changed_keys', v_changed_keys, 'revision', v_workspace.revision)
  );

  return jsonb_build_object('revision', v_workspace.revision, 'updated_at', now());
end;
$$;

create or replace function public.record_audit_event(
  p_action text,
  p_entity_type text default null,
  p_entity_id text default null,
  p_metadata jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_membership public.gym_users%rowtype;
begin
  select * into v_membership from public.gym_users where user_id = auth.uid() and enabled limit 1;
  if not found then raise exception 'GYM_MEMBERSHIP_REQUIRED'; end if;
  if p_action not in (
    'login', 'logout', 'settings_updated', 'backup_restored', 'staff_updated',
    'member_created', 'member_updated', 'member_deleted', 'payment_created',
    'membership_renewed', 'product_sold', 'expense_created', 'expense_updated',
    'inquiry_updated'
  ) then raise exception 'INVALID_AUDIT_ACTION'; end if;
  insert into public.audit_logs (gym_id, user_id, role, action, entity_type, entity_id, metadata)
  values (
    v_membership.gym_id,
    auth.uid(),
    v_membership.role,
    p_action,
    left(p_entity_type, 80),
    left(p_entity_id, 160),
    coalesce(p_metadata, '{}'::jsonb)
  );
end;
$$;

create or replace function public.consume_api_rate_limit(
  p_scope text,
  p_subject text,
  p_limit integer,
  p_window_seconds integer
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row public.api_rate_limits%rowtype;
  v_now timestamptz := now();
  v_window interval;
begin
  if p_limit < 1 or p_limit > 10000 or p_window_seconds < 1 or p_window_seconds > 86400 then
    return false;
  end if;
  v_window := make_interval(secs => p_window_seconds);

  insert into public.api_rate_limits (scope, subject, window_started_at, request_count, updated_at)
  values (left(p_scope, 120), left(p_subject, 200), v_now, 1, v_now)
  on conflict (scope, subject) do update set
    window_started_at = case
      when public.api_rate_limits.window_started_at + v_window <= v_now then v_now
      else public.api_rate_limits.window_started_at
    end,
    request_count = case
      when public.api_rate_limits.window_started_at + v_window <= v_now then 1
      else public.api_rate_limits.request_count + 1
    end,
    updated_at = v_now
  returning * into v_row;

  return v_row.request_count <= p_limit;
end;
$$;

